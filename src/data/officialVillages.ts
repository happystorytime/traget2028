// Helper to project coordinates geographically within Sindhanur AC-58 bounds
// lat: 15.65 - 15.90, lng: 76.62 - 76.95
function calculateCoordinates(index: number, total: number): { lat: number; lng: number } {
  // Golden ratio spiral / grid distribution centered around Sindhanur
  const phi = (index * 137.5 * Math.PI) / 180;
  const radius = 0.03 + (Math.sqrt(index / total) * 0.11);
  const lat = Number((15.775 + radius * Math.cos(phi) * 0.9).toFixed(4));
  const lng = Number((76.765 + radius * Math.sin(phi) * 1.2).toFixed(4));
  return { lat, lng };
}

